-- HÔM NAY · 4 BẢNG — SOÁT TRÊN DỮ LIỆU THẬT (CHỈ ĐỌC, 01/11 · đếm lại 02/11 sau tính BAN_BON 4 = v3 ca thi + lên bảng, v3b hai trục bỏ «Đang theo dõi», PR #741).
-- Một câu SELECT, chỉ SỐ ĐẾM GỘP: không SBD, không tên (repo công khai). Cột v3 chỉ tính trên dòng đã tính lại `ban = 4`.
-- PHẢI = 0: chua_xep_bang_nao, sai_truc_cong_suc, chong_ht_dp, dang_theo_doi_ban4. chua_co_ban_tinh = em đang học chưa có dòng (cron chưa tới lượt).
SELECT
  COUNT(*) AS so_em,
  (SELECT COUNT(*) FROM hoc_sinh h WHERE COALESCE(h.trang_thai, '') NOT IN ('khoa', 'da_nghi')) AS hoc_sinh_dang_hoc,
  (SELECT COUNT(*) FROM hoc_sinh h WHERE COALESCE(h.trang_thai, '') NOT IN ('khoa', 'da_nghi') AND NOT EXISTS (SELECT 1 FROM bon_chi_so_em b WHERE b.sbd = h.sbd)) AS chua_co_ban_tinh,
  SUM(json_extract(so_lieu_json, '$.ban') = 4) AS da_tinh_ban4,
  SUM(COALESCE(json_extract(so_lieu_json, '$.ban'), 0) < 4) AS con_ban_cu,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1) AS bang_hoc_that,
  SUM(json_extract(so_lieu_json, '$.vao.dp') = 1) AS bang_doi_pho,
  SUM(json_extract(so_lieu_json, '$.vao.ch') = 1) AS bang_cham,
  SUM(json_extract(so_lieu_json, '$.vao.lu') = 1) AS bang_luoi,
  SUM(json_extract(so_lieu_json, '$.ban') = 4 AND COALESCE(json_extract(so_lieu_json, '$.vao.ht'), 0) + COALESCE(json_extract(so_lieu_json, '$.vao.dp'), 0) + COALESCE(json_extract(so_lieu_json, '$.vao.ch'), 0) + COALESCE(json_extract(so_lieu_json, '$.vao.lu'), 0) = 0) AS chua_xep_bang_nao,
  SUM(json_extract(so_lieu_json, '$.ban') = 4 AND COALESCE(json_extract(so_lieu_json, '$.vao.ch'), 0) + COALESCE(json_extract(so_lieu_json, '$.vao.lu'), 0) <> 1) AS sai_truc_cong_suc,
  SUM(json_extract(so_lieu_json, '$.ban') = 4 AND COALESCE(json_extract(so_lieu_json, '$.vao.ht'), 0) + COALESCE(json_extract(so_lieu_json, '$.vao.dp'), 0) = 0) AS khong_nhan_chat_luong,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1 AND json_extract(so_lieu_json, '$.vao.dp') = 1) AS chong_ht_dp,
  SUM(json_extract(so_lieu_json, '$.ban') = 4 AND json_extract(so_lieu_json, '$.theoDoi') IS NOT NULL) AS dang_theo_doi_ban4,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1 AND json_extract(so_lieu_json, '$.vao.lu') = 1) AS ht_va_luoi,
  SUM(json_extract(so_lieu_json, '$.vao.dp') = 1 AND json_extract(so_lieu_json, '$.vao.ch') = 1) AS dp_va_cham,
  SUM(json_extract(so_lieu_json, '$.caCau') > 0) AS co_ca_thi,
  SUM(json_extract(so_lieu_json, '$.caGhep') >= 4) AS co_ca_thi_ghep_don_vi,
  SUM(json_extract(so_lieu_json, '$.bangTong') > 0) AS co_len_bang,
  SUM(json_extract(so_lieu_json, '$.ban') = 4 AND COALESCE(json_extract(so_lieu_json, '$.caCau'), 0) = 0 AND COALESCE(json_extract(so_lieu_json, '$.bangTong'), 0) = 0) AS khong_ca_khong_bang,
  SUM(json_extract(so_lieu_json, '$.caCau')) AS tong_cau_thi,
  SUM(json_extract(so_lieu_json, '$.caGhep')) AS tong_cau_thi_ghep,
  SUM(json_extract(so_lieu_json, '$.bangTong')) AS tong_lan_len_bang,
  SUM(json_extract(so_lieu_json, '$.bangDat')) AS tong_lan_dat,
  SUM(json_extract(so_lieu_json, '$.dvKhop') >= 2 AND json_extract(so_lieu_json, '$.dvLech') = 0) AS ca_thi_khop_2_don_vi,
  SUM(json_extract(so_lieu_json, '$.dvLech') > 0) AS co_don_vi_lech,
  SUM(json_extract(so_lieu_json, '$.ho.lechCa') IS NOT NULL) AS ho_lech_ca,
  SUM(json_extract(so_lieu_json, '$.ho.lechCa') = 3) AS ho_lech_ca_manh_3,
  SUM(json_extract(so_lieu_json, '$.ho.bangChua') IS NOT NULL) AS ho_bang_chua,
  SUM(json_extract(so_lieu_json, '$.nho.ht') = 2) AS vao_ht_nho_ca_bang,
  SUM(json_extract(so_lieu_json, '$.nho.dp') = 2) AS vao_dp_nho_ca_bang,
  SUM(json_extract(so_lieu_json, '$.nho.ht') >= 1) AS ht_co_bang_chung_ca_bang,
  SUM(json_extract(so_lieu_json, '$.nho.dp') >= 1) AS dp_co_bang_chung_ca_bang,
  SUM(json_extract(so_lieu_json, '$.nho.htRa') = 1) AS roi_ht_nho_ca_bang,
  SUM(json_extract(so_lieu_json, '$.nho.dpRa') = 1) AS roi_dp_nho_ca_bang,
  SUM(json_extract(so_lieu_json, '$.ho.voi') IS NOT NULL) AS ho_voi,
  SUM(json_extract(so_lieu_json, '$.ho.lap') IS NOT NULL) AS ho_lap,
  SUM(json_extract(so_lieu_json, '$.ho.treo') IS NOT NULL) AS ho_treo,
  SUM(json_extract(so_lieu_json, '$.ho.lech') IS NOT NULL) AS ho_lech,
  SUM(json_extract(so_lieu_json, '$.ho.nhanh') IS NOT NULL) AS ho_nhanh,
  SUM(json_extract(so_lieu_json, '$.ho.tra') IS NOT NULL) AS ho_tra,
  SUM(json_extract(so_lieu_json, '$.ho.do') IS NOT NULL) AS ho_do,
  SUM(json_extract(so_lieu_json, '$.ho.boMac') IS NOT NULL) AS ho_bo_mac,
  SUM(json_extract(so_lieu_json, '$.ho.thuoc') IS NOT NULL) AS ho_thuoc,
  SUM(json_extract(so_lieu_json, '$.ho.goiY') IS NOT NULL) AS ho_goi_y,
  SUM(json_extract(so_lieu_json, '$.ho.thi') IS NOT NULL) AS ho_thi,
  SUM(json_extract(so_lieu_json, '$.donHan') >= 50) AS don_han_tu_nua,
  ROUND(AVG(ht), 1) AS tb_ht, ROUND(AVG(dp), 1) AS tb_dp, ROUND(AVG(ch), 1) AS tb_ch, ROUND(AVG(lu), 1) AS tb_lu
FROM bon_chi_so_em WHERE json_valid(so_lieu_json);
