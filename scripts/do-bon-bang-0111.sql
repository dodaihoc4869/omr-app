-- HÔM NAY · 4 BẢNG — SOÁT TRÊN DỮ LIỆU THẬT (CHỈ ĐỌC, 01/11; bản v2 «chắc mới xếp»). Một câu SELECT, chỉ SỐ ĐẾM GỘP: không SBD, không tên (repo công khai).
SELECT
  COUNT(*) AS so_em,
  SUM(json_extract(so_lieu_json, '$.ban') = 2) AS da_tinh_v2,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1) AS bang_hoc_that,
  SUM(json_extract(so_lieu_json, '$.vao.dp') = 1) AS bang_doi_pho,
  SUM(json_extract(so_lieu_json, '$.vao.ch') = 1) AS bang_cham,
  SUM(json_extract(so_lieu_json, '$.vao.lu') = 1) AS bang_luoi,
  SUM(json_extract(so_lieu_json, '$.theoDoi') IS NOT NULL) AS dang_theo_doi,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1 AND json_extract(so_lieu_json, '$.vao.lu') = 1) AS chong_ht_lu,
  SUM(json_extract(so_lieu_json, '$.vao.dp') = 1 AND json_extract(so_lieu_json, '$.vao.ch') = 1) AS chong_dp_ch,
  SUM(json_extract(so_lieu_json, '$.vao.ht') = 1 AND json_extract(so_lieu_json, '$.vao.dp') = 1) AS chong_ht_dp,
  SUM(json_extract(so_lieu_json, '$.ho.voi') IS NOT NULL) AS ho_voi,
  SUM(json_extract(so_lieu_json, '$.ho.lap') IS NOT NULL) AS ho_lap,
  SUM(json_extract(so_lieu_json, '$.ho.treo') IS NOT NULL) AS ho_treo,
  SUM(json_extract(so_lieu_json, '$.ho.lech') IS NOT NULL) AS ho_lech,
  SUM(json_extract(so_lieu_json, '$.ho.nhanh') IS NOT NULL) AS ho_nhanh,
  SUM(json_extract(so_lieu_json, '$.ho.tra') IS NOT NULL) AS ho_tra,
  SUM(json_extract(so_lieu_json, '$.ho.boMac') IS NOT NULL) AS ho_bo_mac,
  SUM(json_extract(so_lieu_json, '$.ho.thuoc') IS NOT NULL) AS ho_thuoc,
  SUM(json_extract(so_lieu_json, '$.ho.goiY') IS NOT NULL) AS ho_goi_y,
  SUM(json_extract(so_lieu_json, '$.ho.thi') IS NOT NULL) AS ho_thi,
  SUM(json_extract(so_lieu_json, '$.donHan') >= 50) AS don_han_tu_nua,
  SUM(json_extract(so_lieu_json, '$.hoi') > 0) AS co_chu_dong_hoi,
  ROUND(AVG(ht), 1) AS tb_ht, ROUND(AVG(dp), 1) AS tb_dp, ROUND(AVG(ch), 1) AS tb_ch, ROUND(AVG(lu), 1) AS tb_lu
FROM bon_chi_so_em WHERE json_valid(so_lieu_json);
